    public static object FormatLocation(Location loc)
    {
        if (!loc.IsInSource || loc.SourceTree is null)
            return new { inSource = false, metadata = loc.MetadataModule?.Name };

        var lr = loc.SourceTree.LineRange(loc.SourceSpan);
        var text = loc.SourceTree.GetText();
        var lineText = lr.StartLine - 1 >= 0 && lr.StartLine - 1 < text.Lines.Count
            ? text.Lines[lr.StartLine - 1].ToString().Trim()
            : "";

        return new SourceLocationInfo(
            File: string.IsNullOrWhiteSpace(loc.SourceTree.FilePath) ? "Source.cs" : Path.GetFileName(loc.SourceTree.FilePath),
            FullPath: loc.SourceTree.FilePath,
            StartLine: lr.StartLine,
            StartColumn: lr.StartColumn,
            EndLine: lr.EndLine,
            EndColumn: lr.EndColumn,
            SpanStart: loc.SourceSpan.Start,
            SpanLength: loc.SourceSpan.Length,
            LineText: lineText);
    }

    public static (int Errors, int Warnings, DiagnosticItem[] Diagnostics) GetCompilationDiagnostics(string source, WorkspaceContext? existingCtx = null)
    {
        var tree = CSharpSyntaxTree.ParseText(source, CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Preview), "Modified.cs");
        var trees = new List<SyntaxTree> { tree };

        if (existingCtx is not null)
        {
            foreach (var d in existingCtx.Documents)
            {
                if (d.Id != existingCtx.PrimaryDocument.Id)
                    trees.Add(d.Tree);
            }
        }
        else
        {
            trees.Add(CSharpSyntaxTree.ParseText(ImplicitGlobalUsingsSource, path: "__ImplicitGlobalUsings.g.cs"));
        }

        var comp = CSharpCompilation.Create(
            "ValidationCompilation",
            trees,
            DefaultReferences,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true, nullableContextOptions: NullableContextOptions.Enable));

        var diags = comp.GetDiagnostics()
            .Where(d => d.Location.SourceTree == tree && d.Severity >= DiagnosticSeverity.Warning)
            .OrderByDescending(d => d.Severity)
            .ThenBy(d => d.Location.SourceSpan.Start)
            .ToArray();

        int errors = diags.Count(d => d.Severity == DiagnosticSeverity.Error);
        int warnings = diags.Count(d => d.Severity == DiagnosticSeverity.Warning);

        var formatted = diags.Take(50).Select(d =>
        {
            var lr = tree.LineRange(d.Location.SourceSpan);
            return new DiagnosticItem(d.Id, d.Severity.ToString(), d.GetMessage(), lr.StartLine, lr.StartColumn);
        }).ToArray();

        return (errors, warnings, formatted);
    }

    /// <summary>
    /// Shared post-processor for AST mutations: formats the new root, optionally persists to disk,
    /// computes compilation diagnostics before/after, and computes the inline diff.
    /// </summary>
    public static MutationOutcome FinalizeMutation(
        WorkspaceContext ctx,
        DocumentEntry doc,
        SyntaxNode newRoot,
        bool writeToDisk)
    {
        var formattedSource = newRoot.FormatWithRoslyn();
        bool saved = false;
        if (writeToDisk && !string.IsNullOrWhiteSpace(doc.FilePath) && File.Exists(doc.FilePath))
        {
            File.WriteAllText(doc.FilePath, formattedSource);
            saved = true;
        }

        int errorsBefore = doc.Model.GetDiagnostics().Count(d => d.Severity == DiagnosticSeverity.Error);
        var (errorsAfter, warningsAfter, diags) = GetCompilationDiagnostics(formattedSource, ctx);
        var diff = RoslynHelpers.BuildDiff(doc.Source, formattedSource);

        return new MutationOutcome(doc.Name, formattedSource, saved, errorsBefore, errorsAfter, warningsAfter, diags, diff);
    }

    public static string ExtractXmlSummary(ISymbol symbol) => symbol.GetXmlSummary();

    public static string[] GetSymbolModifiers(ISymbol symbol) => symbol.GetModifiers();
