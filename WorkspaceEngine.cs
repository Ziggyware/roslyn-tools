    private static ImmutableArray<MetadataReference> LoadDefaultReferences()
    {
        var paths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        if (AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") is string tpa && !string.IsNullOrWhiteSpace(tpa))
        {
            foreach (var p in tpa.Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries))
            {
                if (File.Exists(p) && p.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                    paths.Add(p);
            }
        }

        Type[] anchorTypes =
        [
            typeof(object), typeof(Console), typeof(Enumerable), typeof(List<>),
            typeof(Task), typeof(JsonSerializer), typeof(Regex), typeof(XDocument),
            typeof(SyntaxNode), typeof(CSharpSyntaxTree), typeof(AdhocWorkspace)
        ];

        foreach (var t in anchorTypes)
        {
            if (!string.IsNullOrWhiteSpace(t.Assembly.Location) && File.Exists(t.Assembly.Location))
                paths.Add(t.Assembly.Location);
        }

        foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
        {
            if (asm.IsDynamic) continue;
            try
            {
                if (!string.IsNullOrWhiteSpace(asm.Location) && File.Exists(asm.Location))
                    paths.Add(asm.Location);
            }
            catch { }
        }

        var builder = ImmutableArray.CreateBuilder<MetadataReference>(paths.Count);
        foreach (var p in paths.OrderBy(x => x, StringComparer.OrdinalIgnoreCase))
        {
            try { builder.Add(MetadataReference.CreateFromFile(p)); }
            catch { }
        }
        return builder.ToImmutable();
    }

