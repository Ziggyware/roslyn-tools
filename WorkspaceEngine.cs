[DebuggerDisplay("{ToString(),nq}")]
internal sealed record DocumentEntry(
    DocumentId Id,
    string Name,
    string? FilePath,
    string Source,
    SyntaxTree Tree,
    SemanticModel Model,
    bool IsSynthetic = false)
{
    public override string ToString() =>
        $"DocumentEntry({Name}, lines={Tree.GetText().Lines.Count}, synthetic={IsSynthetic}, path={FilePath ?? "in-memory"})";
}

[DebuggerDisplay("{ToString(),nq}")]
internal sealed record ResolvedTarget(
    DocumentEntry Document,
    SyntaxNode Node,
    ISymbol? Symbol,
    int Position,
    int Line,
    int Column)
{
    public override string ToString() =>
        $"ResolvedTarget({Document.Name}@L{Line}:{Column} [pos={Position}], node={Node.Kind()}, symbol={Symbol?.MinDisplay() ?? "none"})";
}

[DebuggerDisplay("{ToString(),nq}")]
internal sealed record SourceLocationInfo(
    string File,
    string? FullPath,
    int StartLine,
    int StartColumn,
    int EndLine,
    int EndColumn,
    int SpanStart,
    int SpanLength,
    string LineText)
{
    public override string ToString() => $"{File}:L{StartLine}:{StartColumn}-L{EndLine}:{EndColumn} ({LineText})";
}

[DebuggerDisplay("{ToString(),nq}")]
internal sealed class WorkspaceContext : IDisposable
{
    public AdhocWorkspace Workspace { get; }
    public Solution Solution { get; set; }
    public Project PrimaryProject { get; }
    public CSharpCompilation Compilation { get; }
    public IReadOnlyList<DocumentEntry> Documents { get; }
    public bool IsFromDisk { get; }
    public string? RootPath { get; }

    public WorkspaceContext(
        AdhocWorkspace workspace,
        Solution solution,
        Project primaryProject,
        CSharpCompilation compilation,
        IReadOnlyList<DocumentEntry> documents,
        bool isFromDisk,
        string? rootPath)
    {
        Workspace = workspace;
        Solution = solution;
        PrimaryProject = primaryProject;
        Compilation = compilation;
        Documents = documents;
        IsFromDisk = isFromDisk;
        RootPath = rootPath;
    }

    public IEnumerable<DocumentEntry> UserDocuments => Documents.Where(d => !d.IsSynthetic);

    public DocumentEntry PrimaryDocument =>
        UserDocuments.FirstOrDefault() ?? Documents.First();

    public DocumentEntry? FindDocument(string nameOrPath)
    {
        var normalized = nameOrPath.Replace('\\', '/').Trim();
        return UserDocuments.FirstOrDefault(d =>
            string.Equals(d.Name, normalized, StringComparison.OrdinalIgnoreCase) ||
            string.Equals(d.FilePath?.Replace('\\', '/'), normalized, StringComparison.OrdinalIgnoreCase) ||
            (d.FilePath is not null && d.FilePath.Replace('\\', '/').EndsWith("/" + normalized, StringComparison.OrdinalIgnoreCase)) ||
            d.Name.EndsWith(normalized, StringComparison.OrdinalIgnoreCase));
    }

    public void Dispose() => Workspace.Dispose();

    public override string ToString() =>
        $"WorkspaceContext({PrimaryProject.Name}, docs={UserDocuments.Count()}, fromDisk={IsFromDisk}, root={RootPath ?? "in-memory"})";
}

